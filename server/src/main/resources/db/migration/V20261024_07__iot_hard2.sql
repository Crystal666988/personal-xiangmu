ALTER TABLE iot_device ADD COLUMN secret VARCHAR(64) NULL COMMENT '一机一密';
ALTER TABLE iot_device ADD COLUMN firmware_version VARCHAR(32) NULL;
CREATE TABLE IF NOT EXISTS iot_firmware (
    id VARCHAR(64) NOT NULL PRIMARY KEY, version VARCHAR(32) NOT NULL,
    url VARCHAR(500) NOT NULL, size_bytes BIGINT NULL, md5 VARCHAR(64) NULL,
    grey_batch INT NOT NULL DEFAULT 10, state VARCHAR(32) NOT NULL DEFAULT 'CREATED',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS iot_metric_hourly (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL, farm_id VARCHAR(64) NOT NULL, device_id VARCHAR(64) NOT NULL,
    metric VARCHAR(32) NOT NULL, hour_start DATETIME NOT NULL,
    min_v DOUBLE NOT NULL, max_v DOUBLE NOT NULL, avg_v DOUBLE NOT NULL, sample_count INT NOT NULL,
    UNIQUE KEY uk_iot_hourly (device_id, metric, hour_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='小时级降采样';
