// 路由守卫：按登录状态控制登录页与外贸工作台
router.beforeEach(async (to, from, next) => {
  const authStore = useAuthStore()

  // 访问登录页/注册页
  if (to.path === '/login' || to.path === '/register') {
    if (authStore.isLoggedIn) {
      next('/platform/trade-workbench')
    } else {
      next()
    }
    return
  }

  // 访问根路径或平台入口
  if (to.path === '/' || to.path === '/platform') {
    if (authStore.isLoggedIn) {
      next('/platform/trade-workbench')
    } else {
      next('/login')
    }
    return
  }

  // 其他需要登录的页面
  if (to.meta.requiresAuth !== false && !authStore.isLoggedIn) {
    next('/login')
    return
  }

  next()
})

router.afterEach((to) => {
  if (!isLiteEdition(useAuthStore())) return
  if (to.path === '/login') return
  if (!to.path.startsWith('/platform')) return
  sessionStorage.setItem(LITE_LAST_PATH_KEY, to.fullPath)
})

export default router
